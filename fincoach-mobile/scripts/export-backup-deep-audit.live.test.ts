function envFile(path: string) {
  return Object.fromEntries(readFileSync(path, 'utf8').split(/\r?\n/).flatMap((line) => {
    const match = line.match(/^\s*([A-Z][A-Z0-9_]*)\s*=\s*(.*?)\s*$/);
    return match ? [[match[1], match[2].replace(/^(['"])(.*)\1$/, '$2')]] : [];
  }));
}

async function checked<T>(operation: PromiseLike<{ data: T; error: unknown }>): Promise<T> {
  const { data, error } = await operation;
  if (error) throw error;
  return data;
}

// Timestamps regenerated by database update triggers are not financial values.
function comparable(value: unknown, ignorePaths = false): unknown {
  if (Array.isArray(value)) return value.map(item => comparable(item, ignorePaths)).sort((a, b) => JSON.stringify(a).localeCompare(JSON.stringify(b)));
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value)
    .filter(([key]) => key !== 'updated_at' && !(ignorePaths && ['storage_path', 'receipt_image_path', 'icon_image_path'].includes(key)))
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([key, item]) => [key, comparable(item, ignorePaths)]));
  return value;
}

test.skipIf(process.env.FINCOACH_LIVE_BACKUP_TEST !== '1')('real authenticated cloud backup and restore round trip', async () => {
  const mobileEnv = envFile(resolve('.env'));
  const backendEnv = envFile(resolve('../fincoach-backend/.env'));
  const url = mobileEnv.EXPO_PUBLIC_SUPABASE_URL;
  if (url !== backendEnv.SUPABASE_URL) throw new Error('Frontend/backend Supabase projects differ.');
  const options = { auth: { persistSession: false, autoRefreshToken: false, detectSessionInUrl: false } };
  const admin = createClient(url, backendEnv.SUPABASE_SERVICE_ROLE_KEY, options);
  const createdUsers: string[] = [];
  const sessions: SupabaseClient[] = [];
  const uploaded: { bucket: string; path: string }[] = [];
  const checks: { name: string; passed: boolean; detail?: unknown }[] = [];
  const runId = randomUUID();
  let stage = 'create isolated accounts';
  let fatal: unknown;
  const reportPath = resolve('docs/export-backup-v2-live-verification.json');
  const check = (name: string, passed: boolean, detail?: unknown) => {
    checks.push({ name, passed, ...(detail === undefined ? {} : { detail }) });
    console.log(`${passed ? 'PASS' : 'FAIL'} ${name}`);
  };
  const safeError = (error: unknown) => {
    const e = error as { message?: string; code?: string; details?: string; hint?: string };
    return { message: e?.message ?? String(error), code: e?.code, details: e?.details, hint: e?.hint };
  };
  async function account(suffix: string) {
    const email = `fincoach-backup-test-${runId}-${suffix}@example.com`;
    const password = randomBytes(30).toString('base64url');
    const { data, error } = await admin.auth.admin.createUser({ email, password, email_confirm: true,
      user_metadata: { full_name: 'Disposable backup verification', verification_run: runId } });
    if (error) throw error;
    if (!data.user) throw new Error('Test user was not created.');
    createdUsers.push(data.user.id);
    const client = createClient(url, mobileEnv.EXPO_PUBLIC_SUPABASE_PUBLISHABLE_KEY, options);
    const signIn = await client.auth.signInWithPassword({ email, password });
    if (signIn.error) throw signIn.error;
    sessions.push(client);
    return { client, userId: data.user.id };
  }
  try {
    const { client, userId } = await account('owner');
    const other = await account('other');
    const dataClient = client as unknown as backupApi.ExportBackupDataClient;
    const deps: BackupOrchestratorDependencies = {
      now: () => new Date(), appVersion: '1.0.0-live-verification',
      createBackupRecord: (id, type, name) => backupApi.createBackupRecord(id, type, name, dataClient),
      updateBackupRecord: (id, owner, updates) => backupApi.updateBackupRecord(id, owner, updates, dataClient),
      fetchBackupSourceData: (id, backupId) => backupApi.fetchBackupSourceData(id, dataClient, backupId),
      completeBackup: (id, doc, path, size, checksum) => backupApi.completeFinancialBackup(id, doc, path, size, checksum, dataClient),
      captureAttachments: async (id, backupId, source) => {
        const assets = await captureBackupAttachments(id, backupId, source, dataClient);
        for (const asset of assets) uploaded.push({ bucket: 'financial-backups', path: asset.backupPath });
        return assets;
      },
      cleanupAttachments: (id, backupId) => removeBackupAttachmentCopies(id, backupId, dataClient),
      removeUploadedObject: path => backupApi.removeBackupObject(path, dataClient),
      uploadBackupObject: async (path, bytes) => {
        const result = await backupApi.uploadBackupObject(path, bytes, dataClient);
        uploaded.push({ bucket: 'financial-backups', path });
        return result;
      },
      fetchBackups: (id, limit) => backupApi.fetchBackups(id, limit, dataClient),
      deleteBackup: (record) => backupApi.deleteBackup(record, dataClient),
      fetchAutoBackupEnabled: (id) => backupApi.fetchAutoBackupEnabled(id, dataClient),
      digest: async (content) => createHash('sha256').update(content, 'utf8').digest('hex'),
    };
    stage = 'seed representative records';
    await checked(client.from('profiles').update({ full_name: 'Backup 测试 café', monthly_allowance: 1200,
      spending_records_consent: 'granted', auto_backup_enabled: false }).eq('id', userId));
    const category = await checked(client.from('categories').insert({ user_id: userId, name: 'Backup test food', type: 'expense', icon: 'restaurant', color: '#123456' }).select().single());
    await checked(client.from('user_categories').insert({ user_id: userId, category_id: category.id }));
    const monthly = await checked(client.from('monthly_budgets').insert({ user_id: userId, month: '2026-10-01', limit_amount: 900 }).select().single());
    await checked(client.from('budgets').insert({ user_id: userId, category_id: category.id, month: '2026-10-01', amount: 300 }));
    const goal = await checked(client.from('savings_goals').insert({ user_id: userId, name: 'Test emergency fund', target_amount: 1000, deadline: '2027-01-01' }).select().single());
    await checked(client.from('savings_contributions').insert({ goal_id: goal.id, amount: 125.50, contributed_on: '2026-10-01', note: 'Fixture contribution' }));
    const transaction = await checked(client.from('transactions').insert({ user_id: userId, category_id: category.id,
      amount: 12.34, transaction_date: '2026-10-01', description: 'Nasi lemak 测试', source: 'manual' }).select().single());
    await checked(client.from('notification_preferences').upsert({ user_id: userId, budget_enabled: false,
      savings_enabled: false, spending_enabled: false, bills_enabled: false, spending_weekday: 1 }));
    const reminder = await checked(client.from('reminders').insert({ user_id: userId, title: 'Test bill', amount: 42.50,
      due_at: '2027-01-15T01:00:00Z', recurrence_anchor_day: 15, enabled: false }).select().single());
    // Alerts are server-created in the product, so only fixture setup uses admin.
    await checked(admin.from('alerts').insert({ user_id: userId, type: 'bill_reminder', title: 'Test alert',
      message: 'Disposable verification fixture', reminder_id: reminder.id, budget_id: monthly.id,
      dedupe_key: `backup-test-${runId}`, delivery_status: 'delivered', delivered_at: new Date().toISOString() }));
    await checked(client.from('reports').insert({ user_id: userId, period: '2026-10', type: 'monthly',
      title: 'Test October report', file_name: 'test-report.pdf', storage_path: `${userId}/test-report.pdf`,
      report_key: `backup-test-${runId}`, start_date: '2026-10-01', end_date: '2026-10-31' }));
    // A small synthetic file verifies the restored report's Storage link; PDF
    // rendering belongs to report tests, not this backup/restore acceptance test.
    const reportBytes = new TextEncoder().encode('%PDF-1.4\n% backup restore test fixture\n%%EOF\n');
    const reportPathInBucket = `${userId}/test-report.pdf`;
    await checked(client.storage.from('financial-reports').upload(reportPathInBucket, reportBytes, { contentType: 'application/pdf' }));
    uploaded.push({ bucket: 'financial-reports', path: reportPathInBucket });
    const baseline = await deps.fetchBackupSourceData(userId);
    const categorySelections = await checked(client.from('user_categories').select().eq('user_id', userId)) ?? [];
    check('representative fixture populated', baseline.transactions.length === 1 && baseline.savingsContributions.length === 1 && baseline.reports.length === 1);

    stage = 'real cloud backup upload and download';
    const record = await performCloudBackup(userId, 'manual', deps);
    check('manual backup marked completed', record.status === 'completed' && !!record.storage_path && !!record.checksum_sha256);
    const blob = await backupApi.downloadBackupObject(record.storage_path!, dataClient);
    const document = await downloadAndValidateBackup(record, userId, deps, blob);
    check('downloaded backup matches source records', isDeepStrictEqual(comparable(document.data), comparable(baseline)), { bytes: blob.size });
    const crossRows = await checked(other.client.from('backups').select('id').eq('id', record.id));
    check('another account cannot read backup metadata', crossRows?.length === 0);
    const crossDownload = await other.client.storage.from('financial-backups').download(record.storage_path!);
    check('another account cannot download private backup', !!crossDownload.error && !crossDownload.data);
    await expect(downloadAndValidateBackup({ ...record, checksum_sha256: 'wrong-checksum' }, userId, deps, blob)).rejects.toThrow('checksum does not match');
    check('corrupt checksum rejected before restore', true);
    const crossRestore = await other.client.rpc('restore_financial_backup_v2', { payload: document, backup_record_id: record.id, restored_paths: [] });
    check('another account cannot restore owner backup', !!crossRestore.error);

    stage = 'mutate only disposable account records';
    await checked(client.from('transactions').update({ amount: 99.99, description: 'Changed after backup' }).eq('id', transaction.id).eq('user_id', userId));
    await checked(client.from('transactions').insert({ user_id: userId, category_id: category.id, amount: 5,
      transaction_date: '2026-10-02', description: 'Created after backup', source: 'manual' }));
    await checked(client.from('monthly_budgets').update({ limit_amount: 777 }).eq('id', monthly.id).eq('user_id', userId));
    await checked(client.from('profiles').update({ full_name: 'Changed after backup' }).eq('id', userId));
    await checked(client.from('user_categories').delete().eq('user_id', userId));
    const changed = await deps.fetchBackupSourceData(userId);
    check('test data actually differs before restore', changed.transactions.length === 2 && changed.transactions.some((row) => row.amount === 99.99));

    stage = 'verify database rollback after an invalid restore';
    const invalidDocument = structuredClone(document);
    invalidDocument.data.transactions[0].amount = -1;
    const invalidRestore = await client.rpc('restore_financial_backup_v1', { payload: { ...invalidDocument, schemaVersion: 1 }, backup_record_id: record.id });
    check('database rejects invalid transaction in restore', invalidRestore.error?.code === '23514');
    const afterInvalidRestore = await deps.fetchBackupSourceData(userId);
    check('invalid restore rolls back all financial changes', isDeepStrictEqual(comparable(changed), comparable(afterInvalidRestore)));

    stage = 'real database restore RPC';
    try {
      const restored = await backupApi.restoreFinancialBackup(record.id, document, dataClient);
      check('restore RPC succeeds', true, restored);
    } catch (error) {
      check('restore RPC succeeds', false, safeError(error));
      const afterFailure = await deps.fetchBackupSourceData(userId);
      check('failed restore rolls back financial changes', isDeepStrictEqual(comparable(changed), comparable(afterFailure)));
      throw error;
    }
    const after = await deps.fetchBackupSourceData(userId);
    for (const section of Object.keys(baseline) as (keyof BackupSourceData)[]) {
      check(`restored ${section} matches backup`, isDeepStrictEqual(comparable(baseline[section], true), comparable(after[section], true)),
        isDeepStrictEqual(comparable(baseline[section], true), comparable(after[section], true)) ? undefined : { expected: baseline[section], actual: after[section] });
    }
    const selectedAfter = await checked(client.from('user_categories').select().eq('user_id', userId)) ?? [];
    check('selected categories survive restore', isDeepStrictEqual(comparable(categorySelections), comparable(selectedAfter)), { before: categorySelections.length, after: selectedAfter.length });
    const history = await deps.fetchBackups(userId);
    const restoredRecord = history.find((row) => row.id === record.id);
    check('restore completion recorded', restoredRecord?.last_restore_status === 'completed' && !!restoredRecord.last_restored_at);
    check('automatic backup preference preserved', after.profile?.auto_backup_enabled === false);

    const restoredReportPath = after.reports[0]?.storage_path;
    const restoredFile = restoredReportPath
      ? await client.storage.from('financial-reports').download(restoredReportPath)
      : { data: null, error: { message: 'Restored report has no Storage path' } };
    check('restored report still downloads original stored file', !restoredFile.error && !!restoredFile.data &&
      isDeepStrictEqual(new Uint8Array(await restoredFile.data.arrayBuffer()), reportBytes));

    stage = 'verify legacy backup compatibility';
    const legacyDocument = structuredClone(document);
    delete legacyDocument.data.userCategories;
    // Build and download an actual old-format backup to exercise compatibility.
    const legacyJson = serializeBackupDocument(userId, 'legacy-v1', legacyDocument.data);
    const legacyPending = await backupApi.createBackupRecord(userId, 'manual', 'legacy-v1.json', dataClient);
    const legacyPath = `${userId}/manual/${legacyPending.id}-legacy.json`;
    await deps.uploadBackupObject(legacyPath, new TextEncoder().encode(legacyJson).buffer);
    const legacyRecord = await backupApi.updateBackupRecord(legacyPending.id, userId, { status: 'completed', storage_path: legacyPath,
      schema_version: 1, file_size_bytes: Buffer.byteLength(legacyJson), checksum_sha256: await deps.digest(legacyJson) }, dataClient);
    const legacyBlob = await backupApi.downloadBackupObject(legacyRecord.storage_path!, dataClient);
    const legacyValidated = await downloadAndValidateBackup(legacyRecord, userId, deps, legacyBlob);
    await backupApi.restoreFinancialBackup(legacyRecord.id, legacyValidated, dataClient);
    const afterLegacy = await deps.fetchBackupSourceData(userId);
    check('older v1 backup restores without losing current selections', isDeepStrictEqual(comparable(afterLegacy, true), comparable(baseline, true)));

    stage = 'verify automatic backup and explicit empty selections';
    check('disabled automatic backup is skipped', await runEligibleAutomaticBackup(userId, deps) === null);
    await backupApi.updateAutoBackupEnabled(userId, true, dataClient);
    await checked(client.from('user_categories').delete().eq('user_id', userId));
    const autoBaseline = await deps.fetchBackupSourceData(userId);
    const automaticRecord = await runEligibleAutomaticBackup(userId, deps);
    if (!automaticRecord) throw new Error('Eligible automatic backup was not created.');
    check('eligible automatic backup completes', automaticRecord.status === 'completed' && automaticRecord.backup_type === 'automatic');
    const automaticBlob = await backupApi.downloadBackupObject(automaticRecord.storage_path!, dataClient);
    const automaticDocument = await downloadAndValidateBackup(automaticRecord, userId, deps, automaticBlob);
    check('automatic backup content matches source', isDeepStrictEqual(comparable(automaticDocument.data), comparable(autoBaseline)));
    check('recent automatic backup is not duplicated', await runEligibleAutomaticBackup(userId, deps) === null);
    await checked(client.from('user_categories').insert({ user_id: userId, category_id: category.id }));
    await backupApi.restoreFinancialBackup(automaticRecord.id, automaticDocument, dataClient);
    const afterAutomatic = await deps.fetchBackupSourceData(userId);
    check('automatic backup restores full data with empty category selections', isDeepStrictEqual(comparable(afterAutomatic, true), comparable(autoBaseline, true)));
    stage = 'extended export selection, volume, and recovery audit';
    await auditExtendedExportBackup({ client, admin, userId, other: other.client, otherId: other.userId,
      deps, uploaded, check, outputDirectory: resolve('../output/export-backup-v2-20261010') });
  } catch (error) {
    fatal = safeError(error);
    check(`completed stage: ${stage}`, false, fatal);
  } finally {
    // Delete only directories belonging to identities created by THIS run.
    async function cleanFolder(bucket: string, prefix: string) {
      if (!createdUsers.some(id => prefix === id || prefix.startsWith(id + '/'))) throw new Error('Cleanup owner mismatch');
      while (true) {
        const result = await admin.storage.from(bucket).list(prefix, { limit: 100 });
        if (result.error) throw result.error;
        if (!result.data?.length) break;
        for (const entry of result.data) {
          if (!entry.id) await cleanFolder(bucket, `${prefix}/${entry.name}`);
          else await checked(admin.storage.from(bucket).remove([`${prefix}/${entry.name}`]));
        }
      }
    }
    for (const bucket of ['financial-backups', 'financial-reports', 'receipts', 'category-icons']) {
      for (const id of createdUsers) {
        try { await cleanFolder(bucket, id); } catch (error) { check(`fixture Storage cleanup ${bucket}`, false, safeError(error)); }
      }
    }
    // Original objects may already be absent; deleting them again is harmless.
    for (const object of uploaded) {
      const { error } = await admin.storage.from(object.bucket).remove([object.path]);
      check(`temporary ${object.bucket} object removed`, !error, error ? safeError(error) : undefined);
    }
    for (const client of sessions) await client.auth.signOut({ scope: 'global' });
    for (const id of createdUsers) {
      const { error } = await admin.auth.admin.deleteUser(id);
      check('temporary account removed', !error, error ? safeError(error) : undefined);
    }
    if (createdUsers.length) {
      const tables = ['profiles', 'categories', 'transactions', 'monthly_budgets', 'budgets',
        'savings_goals', 'reports', 'reminders', 'alerts', 'notification_preferences', 'user_categories', 'backups', 'data_exports'];
      for (const table of tables) {
        const result = await admin.from(table).select('*', { head: true, count: 'exact' })
          .in(table === 'profiles' ? 'id' : 'user_id', createdUsers);
        check(`cleanup verified: no fixture rows in ${table}`, !result.error && result.count === 0);
      }
      for (const bucket of ['financial-backups', 'financial-reports', 'receipts']) {
        for (const id of createdUsers) {
          const result = await admin.storage.from(bucket).list(id);
          check(`cleanup verified: ${bucket} fixture folder empty`, !result.error && result.data?.length === 0);
        }
      }
    }
    mkdirSync(resolve('docs'), { recursive: true });
    writeFileSync(reportPath, JSON.stringify({ runId, testedAt: new Date().toISOString(), project: new URL(url).hostname,
      environment: 'Node runner, real Supabase Auth/REST/Storage/RPC; no Android device', checks, fatal }, null, 2) + '\n');
    console.log(`Evidence: ${reportPath}`);
  }
  expect(checks.filter((item) => !item.passed), 'Live acceptance failures; see evidence JSON').toEqual([]);
}, 360_000);
